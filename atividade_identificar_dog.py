EPOCHS = 20

history_pt = {
    'loss': [],
    'val_loss': [],
    'accuracy': [],
    'val_accuracy': []
}

best_val_loss = float('inf')
best_weights = None
patience = 4
epochs_without_improvement = 0

for epoch in range(EPOCHS):

    model_pt.train()

    total_loss = 0
    correct = 0
    total = 0

    for images, labels in train_loader:

        images = images.to(device)
        labels = labels.to(device)

        optimizer.zero_grad()

        outputs = model_pt(images)

        loss = criterion(outputs, labels)

        loss.backward()

        optimizer.step()

        total_loss += loss.item() * labels.size(0)

        predictions = (torch.sigmoid(outputs) >= 0.5).float()

        correct += (predictions == labels).sum().item()
        total += labels.size(0)

    train_loss = total_loss / total
    train_acc = correct / total

    # Validação
    model_pt.eval()

    val_loss_total = 0
    val_correct = 0
    val_total = 0

    with torch.no_grad():

        for images, labels in val_loader:

            images = images.to(device)
            labels = labels.to(device)

            outputs = model_pt(images)

            loss = criterion(outputs, labels)

            val_loss_total += loss.item() * labels.size(0)

            predictions = (
                torch.sigmoid(outputs) >= 0.5
            ).float()

            val_correct += (
                predictions == labels
            ).sum().item()

            val_total += labels.size(0)

    val_loss = val_loss_total / val_total
    val_acc = val_correct / val_total

    history_pt['loss'].append(train_loss)
    history_pt['accuracy'].append(train_acc)

    history_pt['val_loss'].append(val_loss)
    history_pt['val_accuracy'].append(val_acc)

    print(
        f"Época {epoch+1}/{EPOCHS} | "
        f"Loss: {train_loss:.4f} | "
        f"Acurácia: {train_acc:.4f} | "
        f"Val Loss: {val_loss:.4f} | "
        f"Val Acc: {val_acc:.4f}"
    )

    if val_loss < best_val_loss:

        best_val_loss = val_loss

        best_weights = {
            k: v.detach().cpu().clone()
            for k, v in model_pt.state_dict().items()
        }

        epochs_without_improvement = 0

    else:

        epochs_without_improvement += 1

    if epochs_without_improvement >= patience:

        print("Early stopping ativado.")
        break

if best_weights is not None:
    model_pt.load_state_dict(best_weights)

