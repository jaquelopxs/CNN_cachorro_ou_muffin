class ChihuahuaMuffinDataset(Dataset):

    def __init__(self, caminhos, rotulos):

        self.caminhos = caminhos
        self.rotulos = rotulos

    def __len__(self):
        return len(self.caminhos)

    def __getitem__(self, idx):

        imagem = Image.open(
            self.caminhos[idx]
        ).convert('RGB')

        imagem = transform(imagem)

        rotulo = torch.tensor(
            self.rotulos[idx],
            dtype=torch.float32
        )

        return imagem, rotulo


