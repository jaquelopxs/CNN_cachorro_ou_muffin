IMG_SIZE = (64, 64)
BATCH_SIZE = 32

def carregar_imagem_tf(caminho, rotulo):

    imagem = tf.io.read_file(caminho)

    imagem = tf.io.decode_image(
        imagem,
        channels=3,
        expand_animations=False
    )

    imagem.set_shape([None, None, 3])

    imagem = tf.image.resize(imagem, IMG_SIZE)

    imagem = tf.cast(imagem, tf.float32) / 255.0

    return imagem, tf.cast(rotulo, tf.float32)


def criar_dataset(X, y, treino=False):

    ds = tf.data.Dataset.from_tensor_slices((X, y))

    ds = ds.map(
        carregar_imagem_tf,
        num_parallel_calls=tf.data.AUTOTUNE
    )

    if treino:
        ds = ds.shuffle(len(X), seed=SEED)

    ds = ds.batch(BATCH_SIZE)
    ds = ds.prefetch(tf.data.AUTOTUNE)

    return ds


