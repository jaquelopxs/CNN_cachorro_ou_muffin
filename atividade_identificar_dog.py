def classificar_imagem_internet(url):

    try:

        resposta = requests.get(
            url,
            timeout=20,
            headers={'User-Agent': 'Mozilla/5.0'}
        )

        resposta.raise_for_status()

        imagem = Image.open(
            BytesIO(resposta.content)
        ).convert('RGB')

        imagem_prep = imagem.resize((64, 64))

        imagem_array = (
            np.array(imagem_prep).astype('float32') / 255.0
        )

        imagem_tensor = np.expand_dims(
            imagem_array, axis=0
        )

        # TensorFlow
        pred_tf = model_tf.predict(
            imagem_tensor,
            verbose=0
        )[0][0]

        classe_tf = (
            'Muffin' if pred_tf >= 0.5 else 'Chihuahua'
        )

        confianca_tf = (
            pred_tf if pred_tf >= 0.5 else 1 - pred_tf
        ) * 100

        # PyTorch
        imagem_pt = transform(imagem).unsqueeze(0).to(device)

        model_pt.eval()

        with torch.no_grad():

            pred_pt = torch.sigmoid(
                model_pt(imagem_pt)
            ).item()

        classe_pt = (
            'Muffin' if pred_pt >= 0.5 else 'Chihuahua'
        )

        confianca_pt = (
            pred_pt if pred_pt >= 0.5 else 1 - pred_pt
        ) * 100

        # Exibição
        plt.figure(figsize=(6, 5))

        plt.imshow(imagem)

        plt.title(
            f"TensorFlow: {classe_tf} ({confianca_tf:.1f}%)\n"
            f"PyTorch: {classe_pt} ({confianca_pt:.1f}%)"
        )

        plt.axis('off')
        plt.show()

        print("RESULTADOS DA CLASSIFICAÇÃO")
        print("-" * 40)

        print(
            f"TensorFlow/Keras: {classe_tf} "
            f"({confianca_tf:.2f}%)"
        )

        print(
            f"PyTorch: {classe_pt} "
            f"({confianca_pt:.2f}%)"
        )

    except Exception as erro:

        print("Não foi possível classificar a imagem:", erro)

